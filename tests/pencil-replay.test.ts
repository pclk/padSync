import type { StrokeData } from "@/lib/types";

// Pencil recordings: record input through the real controller, save it as a file, read it back and
// replay it through the controller again. All input here is synthetic; none of it is from an iPad.

vi.mock("@/ink/render", () => ({ strokePath: vi.fn(() => ({})), seedPath: vi.fn(), paintStroke: vi.fn(), cachedPath: vi.fn() }));
vi.mock("@/lib/store", () => ({ putEntities: vi.fn(), newEntity: vi.fn(), logEvent: vi.fn(), setDeleted: vi.fn(), moveStrokes: vi.fn() }));
vi.mock("@/lib/db", () => ({ db: {}, deviceId: () => "dev" }));

const FIXTURES = join(__dirname, "fixtures", "pencil");
const tool = { kind: "pen" as const, penColor: "#111111", penSize: 3, hlColor: "#fde047", hlSize: 20, eraserSize: 20 };

type Ev = Record<string, unknown>;
const pt = (type: string, id: number, x: number, y: number, t: number, extra: Ev = {}) =>
  ({
    type,
    pointerType: "pen",
    pointerId: id,
    button: type === "pointermove" ? -1 : 0,
    buttons: type === "pointerdown" || type === "pointermove" ? 1 : 0,
    clientX: x,
    clientY: y,
    pressure: type === "pointerup" ? 0 : 0.3 + ((t * 7) % 5) / 10,
    timeStamp: t,
    altitudeAngle: 1.1,
    azimuthAngle: 0.4,
    tiltX: 12,
    tiltY: -3,
    preventDefault() {},
    ...extra,
  }) as unknown as PointerEvent;

/** A move carrying coalesced samples, as Safari delivers Pencil input at 240 Hz. */
const coalescedMove = (id: number, samples: [number, number, number][], extra: Ev = {}) => {
  const co = samples.map(([x, y, t]) => pt("pointermove", id, x, y, t, extra));
  const last = co[co.length - 1];
  return Object.assign(Object.create(null), last, {
    getCoalescedEvents: () => co,
    getPredictedEvents: () => [pt("pointermove", id, last.clientX + 1.37, last.clientY + 0.51, last.timeStamp + 4.2)],
  }) as PointerEvent;
};

const rect = { left: 40.5, top: 113.25, width: 1376, height: 900 };
const sectionEl = (r = rect) => ({ getBoundingClientRect: () => ({ ...r }), setPointerCapture() {} }) as unknown as HTMLElement;

/** Writes "hi" with a dot, a cancelled stroke, a lost capture and a stray tap, recording it all. */
async function record() {
  const { InkController } = await import("@/ink/controller");
  const { PencilRecorder } = await import("@/ink/recorder");
  const box: { c?: InstanceType<typeof InkController> } = {};
  const rec = new PencilRecorder({ label: "Synthetic hi", source: "synthetic", state: () => ({ tool: box.c!.tool, zoom: box.c!.zoom }) });
  const c = (box.c = new InkController("nb", tool, { onSelection() {}, onDragging() {}, onTextCreate() {}, onInput: rec.input, onCommit: rec.commit }, { persist: false, now: () => 1_700_000_000_000 }));
  c.configure(tool, 1.25);
  const sec = { id: "sec-a", el: sectionEl(), strokes: () => [] };
  let t = 1000.123;
  const step = () => (t += 4.1666);
  // h: a down stroke, then the hump.
  c.down(pt("pointerdown", 1, 100, 200, t), sec);
  for (let i = 0; i < 6; i++) c.move(coalescedMove(1, [[100 + i * 0.13, 205 + i * 9.7, step()], [100.2 + i * 0.13, 210 + i * 9.7, step()]]), sec);
  c.up(pt("pointerup", 1, 101, 262, step()), sec);
  t += 180;
  c.down(pt("pointerdown", 2, 101, 240, t), sec);
  for (let i = 0; i < 5; i++) c.move(coalescedMove(2, [[104 + i * 4.3, 236 - i * 1.1 + i * i, step()]]), sec);
  c.up(pt("pointercancel", 2, 125, 250, step()), sec);
  // The capture is lost mid-stroke (system gesture); the later pointerup is harmless.
  t += 150;
  c.down(pt("pointerdown", 3, 150, 230, t), sec);
  for (let i = 0; i < 4; i++) c.move(coalescedMove(3, [[150.4, 235 + i * 7.31, step()], [150.6, 238 + i * 7.31, step()]]), sec);
  c.lostCapture(pt("lostpointercapture", 3, 150.6, 260, step()), sec);
  c.up(pt("pointerup", 3, 150.6, 260, step()), sec);
  // A firm dot over the i, held long enough to count.
  t += 120;
  c.down(pt("pointerdown", 4, 151, 210, t, { pressure: 0.4 }), sec);
  t += 70;
  c.move(coalescedMove(4, [[151.2, 210.3, t]]), sec);
  c.up(pt("pointerup", 4, 151.2, 210.3, t + 2), sec);
  // A brief light bounce: the stray-dot filter drops it.
  t += 300;
  c.down(pt("pointerdown", 5, 300, 300, t, { pressure: 0.02 }), sec);
  c.up(pt("pointerup", 5, 300, 300, t + 8), sec);
  // A finger on the page: recorded, rejected by the controller.
  c.down(pt("pointerdown", 6, 400, 400, t + 20, { pointerType: "touch" }), sec);
  c.up(pt("pointerup", 6, 400, 400, t + 40, { pointerType: "touch" }), sec);
  // A hover move after it all.
  c.move(pt("pointermove", 7, 410, 410, t + 60, { buttons: 0 }), sec);
  return rec.finish("Generated by tests/pencil-replay.test.ts; not hardware input.");
}

beforeEach(() => {
  vi.stubGlobal("requestAnimationFrame", () => 1);
  vi.stubGlobal("cancelAnimationFrame", () => {});
  vi.stubGlobal("window", { devicePixelRatio: 2, innerWidth: 1376, innerHeight: 1032 });
});
afterEach(() => vi.unstubAllGlobals());

describe("pencil recording files", () => {
  it("records raw samples unrounded, with pointer context, coalesced and predicted samples", async () => {
    const r = await record();
    expect(r.source).toBe("synthetic");
    expect(r.events.map((e) => e.seq)).toEqual(r.events.map((_, i) => i));
    const first = r.events[0];
    expect(first).toMatchObject({ kind: "down", type: "pointerdown", section: "sec-a", pointerId: 1, zoom: 1.25, rect });
    expect(first.sample.timeStamp).toBe(1000.123);
    expect(first.sample.tiltX).toBe(12);
    expect(first.tool).toEqual(tool);
    expect(r.events[1].tool).toBeUndefined();
    expect(r.events[1].coalesced).toHaveLength(2);
    expect(r.events[1].predicted).toHaveLength(1);
    expect(r.events.some((e) => e.type === "pointercancel")).toBe(true);
    expect(r.events.some((e) => e.kind === "lost")).toBe(true);
    expect(r.events.some((e) => e.pointerType === "touch")).toBe(true);
    // h, its hump (cancelled but kept), the i stem, the dot. Not the bounce or the finger.
    expect(r.committed).toHaveLength(4);
    expect(r.timeOrigin).toBe(1000.123);
  });

  it("round-trips through the file format exactly", async () => {
    const { parseRecording, serializeRecording } = await import("@/ink/recording");
    const r = await record();
    const text = serializeRecording(r);
    const back = parseRecording(text);
    expect(back.ok).toBe(true);
    if (!back.ok) return;
    expect(back.recording).toEqual(r);
    expect(serializeRecording(back.recording)).toBe(text);
    expect(Object.isFrozen(back.recording.events[3].coalesced![0])).toBe(true);
  });

  it("rejects bad files with errors that name the field", async () => {
    const { parseRecording, serializeRecording, MAX_RECORDING_BYTES } = await import("@/ink/recording");
    const r = await record();
    // eslint-disable-next-line @typescript-eslint/no-explicit-any -- free-form JSON being broken on purpose
    const bad = (mut: (j: Record<string, any>) => void) => {
      const j = JSON.parse(serializeRecording(r));
      mut(j);
      const out = parseRecording(JSON.stringify(j));
      expect(out.ok).toBe(false);
      return out.ok ? [] : out.errors;
    };
    expect(parseRecording("{nope").ok).toBe(false);
    expect((parseRecording("{nope") as { errors: string[] }).errors[0]).toMatch(/not valid JSON/);
    expect((parseRecording("x".repeat(MAX_RECORDING_BYTES + 1)) as { errors: string[] }).errors[0]).toMatch(/limit/);
    expect(bad((j) => (j.format = "something-else"))[0]).toMatch(/^format:.*not a padSync Pencil recording/);
    expect(bad((j) => (j.version = 9))[0]).toMatch(/^version:/);
    expect(bad((j) => (j.events[2].sample.pressure = 3)).join()).toMatch(/events\[2\]\.sample\.pressure/);
    expect(bad((j) => (j.events[4].sample.clientX = "12")).join()).toMatch(/events\[4\]\.sample\.clientX/);
    expect(bad((j) => j.events.splice(1, 1)).join()).toMatch(/events\[1\]\.seq: expected 1/);
    expect(bad((j) => (j.events[0].section = "ghost")).join()).toMatch(/"ghost" is not listed/);
    expect(bad((j) => (j.events[0].kind = "move")).join()).toMatch(/kind "move" needs type pointermove/);
    expect(bad((j) => (j.events[1].coalesced = Array(300).fill(j.events[1].sample))).join()).toMatch(/events\[1\]\.coalesced/);
  });
});

describe("pencil replay", () => {
  it("replays through the controller to exactly the strokes committed while recording", async () => {
    const { InkController } = await import("@/ink/controller");
    const { replayHeadless, diffStrokes } = await import("@/ink/replay");
    const { parseRecording, serializeRecording } = await import("@/ink/recording");
    const r = await record();
    const parsed = parseRecording(serializeRecording(r));
    if (!parsed.ok) throw new Error(parsed.errors.join("\n"));
    const out = replayHeadless(parsed.recording, InkController);
    expect(diffStrokes(r.committed!, out)).toEqual([]);
    expect(out.map((s) => s.afterSeq)).toEqual(r.committed!.map((c) => c.afterSeq));
    // Twice more: same output, and the frozen recording was never written to.
    const again = replayHeadless(parsed.recording, InkController);
    expect(again).toEqual(out);
    expect(serializeRecording(parsed.recording)).toBe(serializeRecording(r));
  });

  it("is deterministic in t0 too, from the recorded time", async () => {
    const { InkController } = await import("@/ink/controller");
    const { replayHeadless } = await import("@/ink/replay");
    const r = await record();
    const a = replayHeadless(r, InkController).map((s) => s.data.t0);
    expect(a[0]).toBe(Date.parse(r.createdAt));
    expect(new Set(a).size).toBe(a.length);
    expect(replayHeadless(r, InkController).map((s) => s.data.t0)).toEqual(a);
  });

  it("maps onto a section at another position and zoom, keeping section coordinates", async () => {
    const { InkController } = await import("@/ink/controller");
    const { PencilReplayer } = await import("@/ink/replay");
    const r = await record();
    const out: StrokeData[] = [];
    const sec = { id: "lab", el: sectionEl({ left: 7, top: 3, width: 688, height: 450 }), strokes: () => [] };
    const c = new InkController("x", tool, { onSelection() {}, onDragging() {}, onTextCreate() {}, onCommit: (_s, d) => out.push(d) }, { persist: false });
    c.configure(tool, 0.5);
    const p = new PencilReplayer(r, { controller: () => c, section: () => sec, reset() {} });
    p.runToEnd();
    expect(out).toHaveLength(4);
    out.forEach((d, i) => {
      const want = r.committed![i].data.pts;
      d.pts.forEach((v, k) => (k % 6 < 2 ? expect(v).toBeCloseTo(want[k], 1) : expect(v).toBe(want[k])));
    });
  });

  it("plays at the recorded timing and speed, pauses, and steps deterministically", async () => {
    const { InkController } = await import("@/ink/controller");
    const { PencilReplayer } = await import("@/ink/replay");
    const r = await record();
    let now = 0;
    const timers: { at: number; fn: () => void; id: number }[] = [];
    let ids = 0;
    const sched = {
      now: () => now,
      set: (fn: () => void, ms: number) => (timers.push({ at: now + ms, fn, id: ++ids }), ids),
      clear: (h: unknown) => {
        const i = timers.findIndex((x) => x.id === h);
        if (i >= 0) timers.splice(i, 1);
      },
    };
    const advance = (ms: number) => {
      const end = now + ms;
      for (;;) {
        timers.sort((a, b) => a.at - b.at);
        const t = timers[0];
        if (!t || t.at > end) break;
        timers.shift();
        now = t.at;
        t.fn();
      }
      now = end;
    };
    let commits = 0;
    let c!: InstanceType<typeof InkController>;
    const make = () => {
      c = new InkController("x", tool, { onSelection() {}, onDragging() {}, onTextCreate() {}, onCommit: () => commits++ }, { persist: false });
      c.configure(tool, 1.25);
    };
    make();
    const sec = { id: "sec-a", el: sectionEl(), strokes: () => [] };
    const p = new PencilReplayer(r, { controller: () => c, section: () => sec, reset: () => { commits = 0; make(); } }, { scheduler: sched });
    const firstUp = r.events.findIndex((e) => e.kind === "up");
    const upAt = r.events[firstUp].sample.timeStamp - r.timeOrigin;

    p.play();
    advance(upAt - 1);
    expect(p.position).toBe(firstUp);
    expect(commits).toBe(0);
    advance(1);
    expect(commits).toBe(1);
    p.pause();
    const held = p.position;
    advance(10_000);
    expect(p.position).toBe(held);
    expect(p.state).toBe("paused");

    // Restart at double speed: the first stroke ends at half the recorded time.
    p.restart();
    expect(commits).toBe(0);
    p.setSpeed(2);
    p.play();
    advance(upAt / 2);
    expect(commits).toBe(1);
    advance(p.duration);
    expect(p.state).toBe("done");
    expect(commits).toBe(4);

    // Stepping: one event per call, the same strokes as playing.
    p.restart();
    let n = 0;
    while (p.step()) n++;
    expect(n).toBe(r.events.length);
    expect(commits).toBe(4);
    p.restart();
    p.stepTo(upAt);
    expect(commits).toBe(1);
    expect(() => p.setSpeed(0)).toThrow(/positive/);
  });

  it("every fixture recording replays to its committed strokes", async () => {
    const { InkController } = await import("@/ink/controller");
    const { replayHeadless, diffStrokes } = await import("@/ink/replay");
    const { parseRecording, serializeRecording } = await import("@/ink/recording");
    if (process.env.WRITE_PENCIL_FIXTURES) {
      mkdirSync(FIXTURES, { recursive: true });
      writeFileSync(join(FIXTURES, "synthetic-hi.json"), JSON.stringify(JSON.parse(serializeRecording(await record())), null, 1) + "\n");
    }
    const files = readdirSync(FIXTURES).filter((f) => f.endsWith(".json"));
    expect(files.length).toBeGreaterThan(0);
    for (const f of files) {
      const parsed = parseRecording(readFileSync(join(FIXTURES, f), "utf8"));
      if (!parsed.ok) throw new Error(`${f}: ${parsed.errors.join("; ")}`);
      expect(diffStrokes(parsed.recording.committed ?? [], replayHeadless(parsed.recording, InkController)), f).toEqual([]);
    }
  });
});
